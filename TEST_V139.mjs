import assert from 'node:assert/strict';
import fs from 'node:fs';
import {cityInfillRank,V139_CORE_HOUSES,coreFoodAndServices} from './urban-infill-v139.js';
import {ancientWallPlan,surplusForWalls,reserveAfterWalls,wallExtents} from './ancient-walls-v139.js';
import {planAIDefenses} from './ai-defenses-v128.js';
import {Civilization} from './civilization-core.js';
const house=(x=0,z=0)=>({type:'house',x,z,hp:350,ready:true});
const ctx=(c,r,houses)=>({c,r,economy:{buildings:[{type:'hall',virtual:true,hp:1},...Array.from({length:houses},(_,i)=>house((i%6)*8-18,Math.floor(i/6)*8-12))]}});
let centre=ctx(10,10,7),east=ctx(11,10,0);
const game={contextAt:()=>null};
assert.ok(cityInfillRank(centre,centre,'house',game)<cityInfillRank(centre,east,'house',game),'small city builds houses near original hall');
centre=ctx(10,10,20);east=ctx(11,10,6);
assert.ok(cityInfillRank(centre,east,'house',game)<cityInfillRank(centre,centre,'house',game),'established adjoining quarter is infilled before another remote spread');
assert.ok(cityInfillRank(centre,centre,'market',game)<cityInfillRank(centre,east,'market',game),'market remains in civic centre');
assert.deepEqual(coreFoodAndServices([house()],1).slice(0,3),['market','warehouse','cellar']);
const rich={gold:300,wood:220,stone:150,water:150,bread:90,plank:65};
assert.equal(surplusForWalls(rich,20,0),true);
assert.equal(surplusForWalls({...rich,wood:80},20,0),false);
assert.equal(surplusForWalls({...rich,bread:5},20,0),false);
assert.equal(surplusForWalls(rich,20,7),false);
assert.equal(reserveAfterWalls(rich,{wood:30,stone:20}),true);
assert.equal(reserveAfterWalls({...rich,plank:0},{wood:12,stone:2}),true,'wooden palisades do not require a separate plank stockpile');
assert.equal(reserveAfterWalls({...rich,wood:79},{wood:30}),false);
const inner=[house(-30,-19),house(29,18),house(12,-27),house(-14,30)];
const extents=wallExtents(inner,12),ring=ancientWallPlan(inner,'palisade','watchtower',12);
assert.equal(ring.gateOpenings,4);
assert.ok(ring.slots.length>30&&ring.slots.length<100);
assert.ok(ring.slots.filter(s=>s.type==='watchtower').length>=8);
assert.ok(ring.slots.every(p=>Math.abs(p.x)<105&&Math.abs(p.z)<88));
assert.ok(!ring.slots.some(p=>p.type==='palisade'&&Math.abs(p.x)<8&&Math.abs(p.z)===ring.rz),'north/south roads never sealed');
assert.ok(!ring.slots.some(p=>p.type==='palisade'&&Math.abs(p.z)<8&&Math.abs(p.x)===ring.rx),'east/west roads never sealed');
assert.notDeepEqual(ring.slots.map(x=>[x.x,x.z]),ancientWallPlan([...inner,house(71,0),house(72,4),house(68,-3),house(67,7),house(66,1)],'palisade','watchtower',12).slots.map(x=>[x.x,x.z]),'perimeter responds to actual settled buildings');
const town=ctx(10,10,8),realm={pop:20,resources:{...rich}},city={...town,id:2,team:1,economy:{...town.economy,realms:[{},realm]}};
city.economy.buildings.push({type:'market',hp:350,ready:true},{type:'well',hp:350,ready:true});
const mock={s:{time:80,seed:13901,ages:[0,1],units:[]},allBuildings:()=>city.economy.buildings,
  buildRule:(ctx,type)=>['stonewall','stonetower'].includes(type)?'locked':'',
  buildingDefinitions:{palisade:{cost:{wood:8}},watchtower:{cost:{wood:12}},gatehouse:{cost:{wood:20}}},
  build:(ctx,type,p)=>{const building={...p,type,hp:350,ready:true};ctx.economy.buildings.push(building);return {building};}};
planAIDefenses(mock,1,city);
assert.ok(city.defensePlanV139?.slots?.length>30,'wealthy established town gets wall plan');
assert.equal(city.defensePlanV139.constructed,1);
assert.equal(city.economy.buildings.at(-1).historicPerimeterV139,true);
mock.s.time+=60;realm.resources.wood=70;
planAIDefenses(mock,1,city);
assert.equal(city.defensePlanV139.constructed,1,'walls stop when spare construction resources fall');
const s=JSON.parse(fs.readFileSync('scenarios/ai-city-v138.manifest.json'));
assert.equal(s.version,138);
const real=new Civilization(JSON.parse(fs.readFileSync('scenarios/ai-city-v137.json')));
assert.ok(real.s.cities.length>=3);
console.log('V139 PASS: compact centre-first construction, civic diversity, safe four-gate historic walls and resource-sensitive perimeter building');
