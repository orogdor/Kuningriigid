// Pure V163 spatial checks: normal construction, terrain and resource rules still run in the game.
import assert from 'node:assert/strict';
import {historicalBuildingPlots} from './historic-urban-v138.js';
import {STONE_TOWN_V163,stoneTownPlotScore,stoneTownZone,stoneFieldClusterScore} from './stone-town-plan-v163.js';
const hall={type:'hall',x:0,z:0,hp:1200,ready:true};
const parent={c:10,r:10,economy:{buildings:[hall]}};
const radius=p=>Math.hypot(p.x,p.z);
const mean=items=>items.reduce((n,p)=>n+radius(p),0)/items.length;
assert.equal(stoneTownZone('house'),'residential');
assert.equal(stoneTownZone('study'),'civic');
assert.equal(stoneTownZone('well'),'civic');
assert.equal(stoneTownZone('farm'),'rural');
assert.equal(stoneTownZone('lumber'),'rural');
assert.ok(stoneTownPlotScore('house',44,0,23)<stoneTownPlotScore('house',103,0,23),'houses prefer the compact centre');
assert.ok(stoneTownPlotScore('study',27,0,23)<stoneTownPlotScore('study',105,0,23),'civic buildings stay close to the hall');
assert.ok(stoneTownPlotScore('farm',98,0,23)<stoneTownPlotScore('farm',26,0,23),'farmhouses sit beyond the housing zone');
assert.ok(STONE_TOWN_V163.farmRadius>STONE_TOWN_V163.compactLimit,'agriculture outside the settlement');
const homes=historicalBuildingPlots(parent,parent,'house',163,true);
const farms=historicalBuildingPlots(parent,parent,'farm',163,true);
const civic=historicalBuildingPlots(parent,parent,'study',163,true);
assert.ok(homes.length>50&&farms.length>40&&civic.length>30,'planner leaves enough real site candidates');
const houseRadius=mean(homes.slice(0,12)),farmRadius=mean(farms.slice(0,12)),civicRadius=mean(civic.slice(0,12));
assert.ok(houseRadius<STONE_TOWN_V163.compactLimit,'earliest 12 house plots fit in compact core');
assert.ok(farmRadius>houseRadius+25,'first farm plots are outside initial homes');
assert.ok(civicRadius<farmRadius,'civic buildings before outskirts');
assert.deepEqual(homes,historicalBuildingPlots(parent,parent,'house',163,true),'no randomness in city placement');
assert.deepEqual(historicalBuildingPlots(parent,parent,'house',163),historicalBuildingPlots(parent,parent,'house',163,false),'older era default stays unchanged');
const farm={x:80,z:10};
const inner={x:15,z:5},outer={x:88,z:12};
assert.ok(stoneFieldClusterScore(outer,farm,[],outer)<stoneFieldClusterScore(inner,farm,[],inner),'field sites avoid hall');
const nearby={x:90,z:15},remote={x:-70,z:40};
assert.ok(stoneFieldClusterScore(nearby,farm,[{x:89,z:18}],nearby)<stoneFieldClusterScore(remote,farm,[{x:89,z:18}],remote),'fields cluster near the first agricultural plot');
console.log('V163 STONE TOWN PASS',JSON.stringify({first12HouseRadius:Math.round(houseRadius),first12FarmRadius:Math.round(farmRadius),first12CivicRadius:Math.round(civicRadius),houseSites:homes.length,farmSites:farms.length}));
