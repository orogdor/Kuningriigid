import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const designer=read('majaehitaja/index.html');
const module=read('house-builder-v355.js');
const designs=read('house-designs-v354.js');
assert.match(designer,/const wallWalk=\{width:1\.18,deck:2\.22,parapet:(?:\.68|1\.04)\}/);
assert.match(designer,/Rounded bonded stone wall junction/);
assert.match(designer,/Fortress flagstone wall walk/);
assert.match(designer,/Low stone wall continuous coping/);
assert.match(designer,/Open fortress arch ring/);
assert.match(designer,/Octagonal tower corner pier/);
assert.match(designer,/if\(!open\)walkBarrier\(a,b,field\?\.112:\.16,0,leavesHeight\+\.18\)/);
assert.match(designs,/MODEL_VERSION='360a'/);
assert.match(designs,/house-builder-v355\.js\?v=360a/);
const expected=createHash('sha256').update(designer).digest('hex');
assert.match(module,new RegExp('source-sha256: '+expected));
assert.match(module,/Fortress flagstone wall walk/);
console.log('V359 fortress source and generated model in sync');
