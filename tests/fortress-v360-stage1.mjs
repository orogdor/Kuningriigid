import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('majaehitaja/index.html');
const builder=read('house-builder-v355.js');
const designs=read('house-designs-v354.js');
assert.match(html,/const wallWalk=\{width:1\.18,deck:2\.22,parapet:1\.04\}/);
assert.match(html,/function parapetMasonryV360\(/);
assert.match(html,/V360 bonded parapet stone faces/);
assert.match(html,/V360 separate parapet coping stones/);
assert.match(html,/const baseHeight=sign<0\?\.88:\.55/);
assert.match(html,/parapetMasonryV360\(a,b,deck,baseHeight/);
assert.match(html,/parapetMasonryV360\(u,v,deck\+baseHeight/);
assert.doesNotMatch(html,/fortificationMasonry\(a,b,deck,deck\+\.21/);
assert.match(designs,/MODEL_VERSION='360a'/);
assert.match(designs,/house-builder-v355\.js\?v=360a/);
const sha=createHash('sha256').update(html).digest('hex');
assert.match(builder,new RegExp('source-sha256: '+sha));
assert.match(builder,/V360 separate parapet coping stones/);
console.log('V360 phase 1: source, stone geometry and model cache validated');
