// Rebuild independently downloadable, lossless packs from the V148 source packs.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gunzipSync,gzipSync} from 'node:zlib';
const root=fileURLToPath(new URL('../',import.meta.url));
let kinds;
for(const lod of ['high','low']){
 let source=fs.readFileSync(path.join(root,`models-v148/soldiers-v148-${lod}.bin`));
 if(source[0]===31&&source[1]===139)source=gunzipSync(source);
 const length=source.readUInt32LE(4),pack=JSON.parse(source.subarray(8,8+length)),blob=source.subarray(8+length);
 kinds=Object.keys(pack.kinds);
 const dir=path.join(root,'models-v241',lod);fs.mkdirSync(dir,{recursive:true});
 for(const [kind,original] of Object.entries(pack.kinds)){
  const def=structuredClone(original),parts=[];let offset=0;
  for(const chunk of def.chunks)for(const [field,bytes] of [[5,chunk[7]*6],[6,chunk[7]*3],[8,chunk[9]*2]]){
   const padding=(4-offset%4)%4;if(padding){parts.push(Buffer.alloc(padding));offset+=padding;}
   parts.push(blob.subarray(chunk[field],chunk[field]+bytes));chunk[field]=offset;offset+=bytes;
  }
  const json=Buffer.from(JSON.stringify({...pack,kinds:{[kind]:def}})),header=Buffer.alloc(8);
  header.writeUInt32LE(0x3156534B);header.writeUInt32LE(json.length,4);
  fs.writeFileSync(path.join(dir,kind+'.bin'),gzipSync(Buffer.concat([header,json,...parts]),{level:9,mtime:0}));
 }
}
fs.writeFileSync(path.join(root,'soldier-kinds-v241.js'),'// Generated by scripts/split-soldiers-v241.mjs\nexport const SOLDIER_KINDS_V241=Object.freeze('+JSON.stringify(kinds)+');\n');
console.log(`Generated ${kinds.length} separate soldier packs per quality.`);
