import fs from 'node:fs';
import assert from 'node:assert/strict';
import {blocksFutureOuterWallV213} from '../outer-wall-reservation-v213.js';
import {Civilization} from '../civilization-core.js';
const saved=JSON.parse(fs.readFileSync('scenarios/zero-v206-mountain.json','utf8'));
const game=new Civilization(saved),city=game.s.cities.find(c=>c.id===saved.zeroTestV206.targetCityId);
const slot=city.outerRingV184.slots[city.outerRingV184.nextIndex];
assert.ok(slot,'reproduce the actual future wall blocked by a later hunter building');
const land={x:slot.x,z:slot.z};
assert.equal(blocksFutureOuterWallV213(city,land,'hunter'),true);
assert.equal(blocksFutureOuterWallV213(city,land,'house'),true);
assert.equal(blocksFutureOuterWallV213(city,land,'palisade'),false);
assert.equal(blocksFutureOuterWallV213(city,{x:slot.x+500,z:slot.z+500},'hunter'),false);
const st=city.outerRingV184.nextIndex;
city.outerRingV184.nextIndex=city.outerRingV184.slots.length;
assert.equal(blocksFutureOuterWallV213(city,land,'hunter'),false);
city.outerRingV184.nextIndex=st;
const fresh=game.previewBuild(city,'house',{x:slot.x,z:slot.z});
assert.equal(fresh.error,'Planeeritud linnamüüri koridor peab jääma ehitistest vabaks.');
console.log('V213 REAL RESERVED CURTAIN PASS',JSON.stringify({city:city.name,index:st,total:city.outerRingV184.slots.length,block:fresh.error}));
