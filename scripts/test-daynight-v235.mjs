// V235: time-of-day is saved-game deterministic and street torches remain bounded.
import assert from 'node:assert/strict';
import * as T from '../vendor/three.module.js';
import {DAY_LENGTH_V235,START_HOUR_V235,dayClockV235,torchLocationsV235,createCityTorchesV235,updateCityTorchesV235} from '../daynight-v235.js';
import {GRAPHICS_DEFAULTS_V226,LIGHTING_LOOKS_V235} from '../graphics-settings-v226.js';
assert.equal(DAY_LENGTH_V235,1440,'one game day must be 24 real minutes');
assert.equal(START_HOUR_V235,8);
assert.equal(dayClockV235(0).clock,'08:00');
assert.equal(dayClockV235(60).clock,'09:00');
assert.equal(dayClockV235(240).clock,'12:00');
assert.equal(dayClockV235(840).clock,'22:00');
assert.equal(dayClockV235(1440).clock,'08:00');
assert.equal(dayClockV235(1440*4+60).clock,'09:00');
assert.equal(dayClockV235(840).night,true);
assert.equal(dayClockV235(240).night,false);
assert.ok(dayClockV235(840).torch>.9,'torches glow at night');
assert.equal(dayClockV235(240).torch,0,'torches off by day');
assert.ok(GRAPHICS_DEFAULTS_V226.daylight==='dynamic');
assert.ok(GRAPHICS_DEFAULTS_V226.toneMap==='agx');
assert.ok(LIGHTING_LOOKS_V235.natural.toneMap==='agx');
const buildings=[];
for(let i=0;i<80;i++)buildings.push({type:i%11===0?'hall':'house',x:(i%10)*12,z:Math.floor(i/10)*12,hp:100,ready:true});
buildings.push({type:'field',x:120,z:120,hp:100,ready:true});
buildings.push({type:'house',x:140,z:140,hp:0,ready:true});
const locations=torchLocationsV235(buildings);
assert.ok(locations.length>0&&locations.length<=22,'torches limited by performance cap');
assert.ok(locations.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.z)));
const root=createCityTorchesV235(buildings,()=>0);
const models=root.userData.torchModelsV235;
assert.equal(models.length,locations.length);
assert.ok(models.filter(m=>m.light).length<=4,'limit active point lights');
updateCityTorchesV235(root,dayClockV235(840),840);
assert.ok(models.every(m=>m.flame.visible),'all flames lit at night');
assert.ok(models.filter(m=>m.light).every(m=>m.light.intensity>0));
updateCityTorchesV235(root,dayClockV235(240),240);
assert.ok(models.every(m=>!m.flame.visible),'daytime flames hidden');
assert.ok(models.filter(m=>m.light).every(m=>m.light.intensity===0));
console.log('V235 24h cycle / lighting presets / city torches PASS');
