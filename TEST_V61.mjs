import assert from 'node:assert/strict';
import {TECHS,BUILD_TECH,techBlock} from './research.js';
import {BUILDINGS,BUILD_AGE,TROOPS,Civilization,createGame} from './civilization-core.js';
import {initialState} from './economy.js';
import {armyUnits} from './v51-systems.js';
import {createBattle,tickBattle} from './campaign.js';
import {WALL_TYPES,TOWER_TYPES,wallHeight,wallGuards,fortifyBattle} from './fortifications.js?v=61';
import {createAgeBuilding} from './buildings.js';

assert.equal(TECHS.fortifications.age,0);
assert.equal(TECHS.stone_fortifications.age,1);
assert.deepEqual(TECHS.fortifications.requires,['stone_tools','warfare']);
assert.ok(techBlock({known:['stone_tools']},'fortifications'));
assert.equal(techBlock({known:['stone_tools','warfare']},'fortifications'),'');
assert.ok(techBlock({known:['stone_tools','warfare','fortifications']},'stone_fortifications'));
for(const type of ['palisade','watchtower','stonewall','stonetower']){
 assert.ok(BUILDINGS[type]&&BUILD_TECH[type],'missing researched structure '+type);
 const model=createAgeBuilding(type,0,BUILD_AGE[type]);
 assert.ok(model.children.some(x=>x.isMesh),'Fortification needs 3D geometry '+type);
}
assert(WALL_TYPES.has('palisade')&&WALL_TYPES.has('stonewall'));
assert(TOWER_TYPES.has('watchtower')&&TOWER_TYPES.has('stonetower'));
assert(wallHeight('stonewall')>wallHeight('palisade'));
assert.equal(BUILDINGS.watchtower.workers,1);
assert.equal(BUILDINGS.stonetower.workers,1);
const state=createGame(17),game=new Civilization(state),position={c:state.armies[0].c,r:state.armies[0].r},econ=initialState(17);
const city={id:0,team:0,name:'Vana linn',...position,hp:600,economy:econ,world:game.makeWorld(game.cell(position))};
const hall={type:'hall',team:0,x:0,z:0,ready:true,hp:1200};
const wall={type:'palisade',team:0,x:9,z:0,ready:true,hp:350};
const tower={type:'watchtower',team:0,x:-9,z:0,ready:true,hp:350,assigned:1};
econ.buildings=[hall,wall,tower];game.s.cities.push(city);game.prepareCity(city);
const guard={team:0,kind:'archer',hp:100,armyId:0};game.s.units.push(guard);
const army=game.s.armies[0];
assert.equal(armyUnits(game.s,army).length,2);
assert.equal(game.stationWall(city,wall).ok,true,'Must station existing soldier from army');
assert.equal(wallGuards(game.s,city,wall).length,1);
assert.equal(wallGuards(game.s,city,wall)[0].unit,guard);
assert.equal(armyUnits(game.s,army).length,1,'Stationed archer no longer travels with army');
assert.equal(game.stationWall(city,wall).ok,true,'Palisade has two guard slots');
assert.equal(armyUnits(game.s,army).length,0);
assert.match(game.stationWall(city,wall).error,/rohkem/,'Capacity enforced');
const b=createBattle(position,game.s.units);
b.squads=[];b.fortress={team:0,cityId:0,x:0,z:0,hp:600,maxHp:600,cool:0};
fortifyBattle(game,city,b);
assert.equal(b.squads.filter(x=>x.guardPost).length,2);
assert.equal(b.defensePosts.length,1);
assert.equal(b.defensePosts[0].team,0);
assert.ok(b.fortress.hp>600,'Wall and tower add protection');
const attacker={source:98,team:1,kind:'slinger',hp:120,maxHp:120,morale:100,x:-18,z:0,cool:0,target:null};
const siege={cell:position,squads:[attacker],fortress:{team:0,x:0,z:0,hp:600,maxHp:600,cool:10},
 defensePosts:[{team:0,x:-9,z:0,damage:9,range:25,cool:0}],elapsed:0,result:null};
tickBattle(siege,.1,{slinger:{hp:120,dmg:0,range:10,speed:2}},0);
assert.equal(attacker.hp,111,'Manned tower actually shoots');
const idleTower={...tower,assigned:0};
const noCrewCity={...city,economy:{...econ,buildings:[hall,idleTower]}};
const empty={squads:[],fortress:{team:0,hp:600,maxHp:600}};
fortifyBattle(game,noCrewCity,empty);
assert.equal(empty.defensePosts.length,0,'No worker means no tower attack');
const guardBefore=b.squads[0].x;
b.squads.push({source:99,team:1,kind:'slinger',hp:120,maxHp:120,morale:100,x:60,z:0,cool:0,target:null});
b.elapsed=0;b.result=null;
tickBattle(b,.1,TROOPS,0);
assert.equal(b.squads[0].x,guardBefore,'Guard stays assigned to wall');
const saved=JSON.parse(JSON.stringify(game.s)),loaded=new Civilization(saved);
assert.equal(loaded.s.version,4,'Save schema unchanged');
assert.equal(loaded.s.units.filter(u=>u.garrison).length,2,'Garrison persists after reload');
assert.equal(loaded.wallGuards(loaded.s.cities[0],loaded.s.cities[0].economy.buildings[1]).length,2);
assert.equal(loaded.releaseWall(loaded.s.cities[0],loaded.s.cities[0].economy.buildings[1]).ok,true,'Release stationed soldier');
assert.equal(loaded.s.units.filter(u=>u.garrison).length,1);
console.log('V61 PASS: research locks, four 3D structures, real army transfer and capacity, active towers, static guards, saved garnisons');
