import assert from 'node:assert/strict';
import {Navigation} from './navigation.js';
import {wallPointInsideV175} from './wall-draw-v175.js';
const world={resources:[],heat:{},heatLast:{}};
const wall={type:'palisade',x:0,z:0,wallAngleV175:0,palisadeSpanV167:7,hp:350,ready:true,team:0};
const nav=new Navigation(world,()=>true,()=>[wall],{minX:-20,minZ:-20,w:41,h:41});
assert.equal(nav.open(3,0),false,'initial wall blocks its length');
assert.equal(nav.open(0,3),true,'initial wall leaves transverse path');
const before=nav.version;
wall.wallAngleV175=Math.PI/2;
nav.refresh();
assert.ok(nav.version>before,'rotating wall invalidates navigation cache');
assert.equal(nav.open(3,0),true,'old wall footprint opens after rotation');
assert.equal(nav.open(0,3),false,'new wall footprint blocks after rotation');
assert.equal(wallPointInsideV175({x:0,z:3},wall),true);
const blocked=nav.index(0,3);
world.heat[blocked]=60;world.heatLast[blocked]=0;
nav.rebuild();
assert.equal(world.heat[blocked],undefined,'roads inside rotated wall removed');
const gate={type:'woodgate',x:0,z:0,wallAxis:0,hp:350,ready:true,team:0};
const gateNav=new Navigation({resources:[],heat:{},heatLast:{}},()=>true,()=>[gate],{minX:-20,minZ:-20,w:41,h:41});
assert.equal(gateNav.open(0,0),true,'gate center remains walkable');
assert.equal(gateNav.open(3,0),false,'gate post remains solid');
