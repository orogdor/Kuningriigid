import assert from 'node:assert/strict';
import {TileDoubleTap,detailWheelTransition} from './map-gestures-v121.js?v=121a';
import {BUILD_CATEGORIES,buildingCategory,matchesBuilding} from './build-catalog-v121.js?v=121a';
const d=new TileDoubleTap();
const tap=(tile,time,x=100,y=100,pointerType='mouse')=>d.push({tile,time,x,y,pointerType});
assert.equal(tap('1:1',100),false);
assert.equal(tap('1:1',250,108,110),true,'Two fast taps on same tile open detail');
assert.equal(tap('1:1',500),false);
assert.equal(tap('2:2',550),false,'Different tile does not open');
assert.equal(tap('2:2',1200),false,'Old click expires');
assert.equal(tap('2:2',1260,180,110),false,'Distant click is not a double-tap');
assert.equal(tap('2:2',1500),false);
assert.equal(tap('2:2',1750,102,106,'touch'),false,'Touch cannot share a mouse double-tap');
assert.equal(tap('2:2',1950,105,106,'touch'),true,'Touch double-tap opens detail');
d.reset();assert.equal(tap('1:1',2300),false);d.reset();assert.equal(tap('1:1',2350),false,'Dragging resets tapping');
assert.equal(detailWheelTransition({view:'local',zoom:150,deltaY:100}).exitToWorld,false);
assert.equal(detailWheelTransition({view:'local',zoom:449,deltaY:100}).exitToWorld,true);
assert.equal(detailWheelTransition({view:'local',zoom:449,deltaY:-100}).exitToWorld,false);
assert.equal(detailWheelTransition({view:'local',zoom:449,deltaY:500,isBattle:true}).exitToWorld,false,'Cannot leave battle through scroll');
assert.equal(detailWheelTransition({view:'world',zoom:950,deltaY:2000}).exitToWorld,false);
assert.equal(buildingCategory('house'),'housing');
assert.equal(buildingCategory('farm'),'food');
assert.equal(buildingCategory('quarry'),'resources');
assert.equal(buildingCategory('barracks'),'military');
assert.equal(buildingCategory('study'),'science');
assert.equal(buildingCategory('bridge'),'services');
assert.equal(matchesBuilding('quarry','Quarry','resources','quarr'),true);
assert.equal(matchesBuilding('quarry','Quarry','housing',''),false);
assert.equal(matchesBuilding('well','Well','all','well'),true);
assert.equal(BUILD_CATEGORIES.length,7);
console.log('V121 PASS: double mouse/touch, different tile, drag, scroll exit, battle guard, searchable building categories.');
